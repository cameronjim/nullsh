TEST(reply_status_reports_a_non_zero_rcode) {
    DnsHeader hdr = header_of(7, 0);
    hdr.rcode = 3;
    char msg[RESOLVE_MSG_MAX];
    ASSERT_EQ(resolve_reply_status(&hdr, 7, msg, sizeof msg), 1);

    char rcode[WORD_BUF];
    rcode_word(3, rcode, sizeof rcode);
    char want[TEXT_BUF];
    if (dns_rcode_str(3) != NULL) {
        snprintf(want, sizeof want, "server returned %s", rcode);
    } else {
        snprintf(want, sizeof want, "server returned rcode %s", rcode);
    }
    ASSERT_STR_EQ(msg, want);
}

TEST(reply_status_reports_every_non_zero_rcode) {
    for (unsigned code = 1; code <= 15; code++) {
        DnsHeader hdr = header_of(1, 0);
        hdr.rcode = (uint8_t)code;
        char msg[RESOLVE_MSG_MAX];
        ASSERT_EQ(resolve_reply_status(&hdr, 1, msg, sizeof msg), 1);
        ASSERT_TRUE(strncmp(msg, "server returned ", 16) == 0);
    }
}

static void setup(void) {
    snprintf(g_tmp, sizeof g_tmp, "/tmp/nsh_resolve_XXXXXX");
    if (mkdtemp(g_tmp) == NULL) {
        fprintf(stderr, "resolve_test: mkdtemp failed\n");
        exit(1);
    }
}

static void teardown(void) {
    char cmd[CMD_BUF];
    snprintf(cmd, sizeof cmd, "rm -rf %s", g_tmp);
    if (system(cmd) != 0) {
        fprintf(stderr, "resolve_test: could not remove %s\n", g_tmp);
    }
}

// Every conf case writes a fixture into the scratch directory, so main is here.
int main(void) {
    setup();
    int failures = 0;
    for (int i = 0; i < nsh_test_count; i++) {
        int failed = 0;
        nsh_test_cases[i].fn(&failed);
        printf("  %s %s\n", failed ? "FAIL" : "ok  ", nsh_test_cases[i].name);
        failures += failed;
    }
    printf("  %d test(s), %d failed\n", nsh_test_count, failures);
    teardown();
    return failures == 0 ? 0 : 1;
}
