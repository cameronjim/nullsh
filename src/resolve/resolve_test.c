#define PATH_BUF 128
#define TEXT_BUF 1024
#define WORD_BUF 32
#define CMD_BUF 256

static char g_tmp[64];

// One scratch path at a time, which is all any case here needs.
static const char *fixture(const char *base, const char *content) {
    static char path[PATH_BUF];
    snprintf(path, sizeof path, "%s/%s", g_tmp, base);
    FILE *f = fopen(path, "w");
    if (f == NULL) {
        return NULL;
    }
    if (content != NULL) {
        fputs(content, f);
    }
    fclose(f);
    return path;
}

// dns.c is a stub in this clone and names no rcode, so the expected text takes
// whichever word dns_rcode_str yields; at integration that is "NOERROR".
static void rcode_word(uint8_t rcode, char *out, size_t cap) {
    const char *name = dns_rcode_str(rcode);
    if (name != NULL) {
        snprintf(out, cap, "%s", name);
    } else {
        snprintf(out, cap, "%u", (unsigned)rcode);
    }
}

// NULL when the memory stream could not be opened. Caller frees with free.
static char *render(const DnsHeader *hdr, const Vec *answers) {
    char *buf = NULL;
    size_t len = 0;
    FILE *out = open_memstream(&buf, &len);
    if (out == NULL) {
        return NULL;
    }
    resolve_print_reply(hdr, answers, out);
    fclose(out);
    return buf;
}

static DnsHeader header_of(uint16_t id, uint16_t ancount) {
    DnsHeader h;
    memset(&h, 0, sizeof h);
    h.id = id;
    h.qr = true;
    h.rd = true;
    h.ra = true;
    h.qdcount = 1;
    h.ancount = ancount;
    return h;
}

static DnsRecord record_of(const char *name, uint32_t ttl, uint16_t type) {
    DnsRecord r;
    memset(&r, 0, sizeof r);
    snprintf(r.name, sizeof r.name, "%s", name);
    r.ttl = ttl;
    r.type = type;
    r.qclass = DNS_CLASS_IN;
    return r;
}

static DnsRecord a_record(const char *name, uint32_t ttl, uint8_t a, uint8_t b,
                          uint8_t c, uint8_t d) {
    DnsRecord r = record_of(name, ttl, DNS_TYPE_A);
    r.rdlength = 4;
    r.addr[0] = a;
    r.addr[1] = b;
    r.addr[2] = c;
    r.addr[3] = d;
    return r;
}

static DnsRecord cname_record(const char *name, uint32_t ttl,
                              const char *target) {
    DnsRecord r = record_of(name, ttl, DNS_TYPE_CNAME);
    snprintf(r.target, sizeof r.target, "%s", target);
    r.rdlength = (uint16_t)(strlen(target) + 2);
    return r;
}

