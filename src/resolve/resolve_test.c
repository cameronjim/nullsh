// Output, pinned byte for byte

TEST(output_matches_the_pinned_cname_then_a_example) {
    DnsHeader hdr = header_of(4242, 2);
    DnsRecord cname = cname_record("example.com", 300, "edge.example.net");
    DnsRecord a = a_record("edge.example.net", 60, 93, 184, 216, 34);
    Vec answers;
    vec_init(&answers);
    vec_push(&answers, &cname);
    vec_push(&answers, &a);

    char *got = render(&hdr, &answers);
    vec_free(&answers);
    ASSERT_TRUE(got != NULL);

    char rcode[WORD_BUF];
    rcode_word(0, rcode, sizeof rcode);
    char want[TEXT_BUF];
    snprintf(want, sizeof want,
             ";; id 4242 flags qr rd ra rcode %s answers 2\n"
             "example.com. 300 IN CNAME edge.example.net.\n"
             "edge.example.net. 60 IN A 93.184.216.34\n",
             rcode);

    int same = strcmp(got, want);
    if (same != 0) {
        printf("    got:  [%s]\n    want: [%s]\n", got, want);
    }
    free(got);
    ASSERT_EQ(same, 0);
}

